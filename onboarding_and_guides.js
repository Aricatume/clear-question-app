  function renderGuideBox(toolKey) {
    const g = TOOL_GUIDES[toolKey];
    if (!g) return "";
    const openAttr = isGuideOpenByDefault(toolKey) ? "open" : "";
    return `
      <details class="guide-passport" data-guide-key="${esc(toolKey)}" ${openAttr}>
        <summary class="guide-passport-sum">
          <span>💡 <strong>Зачем в жизни и как работает:</strong> ${esc(g.title)}</span>
          <span class="guide-passport-chev">▾</span>
        </summary>
        <div class="guide-passport-body">
          <div class="gp-row"><span class="gp-tag why">Зачем</span><span>${esc(g.why)}</span></div>
          <div class="gp-row"><span class="gp-tag how">Механика</span><span>${esc(g.how)}</span></div>
          <div class="gp-row"><span class="gp-tag ex">Пример</span><span>${esc(g.example)}</span></div>
          <div class="gp-row"><span class="gp-tag lim">Граница</span><span>${esc(g.limit)}</span></div>
        </div>
      </details>
    `;
  }

  function bindGuideBox(container) {
    if (!container) return;
    container.querySelectorAll("details.guide-passport").forEach((det) => {
      det.addEventListener("toggle", () => {
        const key = det.getAttribute("data-guide-key");
        if (key) setGuideCollapsed(key, !det.open);
      });
    });
  }

